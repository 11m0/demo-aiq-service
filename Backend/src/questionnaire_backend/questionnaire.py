def build_initial_state(questionnaire: QuestionnaireDefinition) -> QuestionnaireState:
    """
    Создаёт нулевой снимок со всеми вопросами в статусе UNKNOWN.
    """
    return QuestionnaireState(
        state_version=0,
        questionnaire_code=questionnaire.questionnaire_code,
        questionnaire_version=questionnaire.questionnaire_version,
        questions=tuple(
            QuestionState(question_code=question.question_code)
            for question in questionnaire.questions
        ),
    )
