def _scale_options(*labels: str) -> tuple[QuestionOption, ...]:
    """
    Создаёт четыре варианта шкалы с кодами O0–O3 и значениями 0–3.
    """
    return tuple(
        QuestionOption(
            option_code=f"O{numeric_value}",
            text=label,
            numeric_value=numeric_value,
        )
        for numeric_value, label in enumerate(labels)
    )


def _scale_question(
    *,
    code: str,
    text: str,
    labels: tuple[str, str, str, str],
    answer_meaning: str,
    prompt_hint: str,
    followup_clarification_text: str | None = None,
) -> Question:
    """
    Создаёт вопрос шкалы 0–3 с согласованным текстом уточнения.
    """
    return Question(
        question_code=code,
        question_type=QuestionType.SCALE_0_3,
        question_text=text,
        answer_meaning=answer_meaning,
        options=_scale_options(*labels),
        prompt_hint=prompt_hint,
        clarification_text=_CLARIFICATION_TEXTS[code],
        followup_clarification_text=followup_clarification_text,
    )


