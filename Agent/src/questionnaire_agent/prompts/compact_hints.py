def compact_prompt_hint(code: str, original_hint: str) -> str:
    """
    Возвращает краткую подсказку только для неизменённой исходной версии.
    """
    compact = COMPACT_HINTS.get(code)
    expected_digest = ORIGINAL_HINT_SHA256.get(code)
    if compact is None or expected_digest is None:
        return original_hint
    if sha256(original_hint.encode("utf-8")).hexdigest() != expected_digest:
        return original_hint
    return compact
