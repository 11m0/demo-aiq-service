    pending = request.state.pending_clarification
    pending_payload = (
        None
        if pending is None
        else {
            "questionCode": pending.question_code,
            "reason": pending.reason,
        }
    )
    clarification_context_ids = (
        frozenset() if pending is None else frozenset(pending.context_message_ids)
    )
    active_question = request.active_question
    active_definition = next(
        (
            question
            for question in request.questionnaire.questions
            if active_question is not None
            and question.question_code == active_question.question_code
        ),
        None,
    )
    correction = request.answer_correction
