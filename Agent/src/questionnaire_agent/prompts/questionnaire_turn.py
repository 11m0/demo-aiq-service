def _build_replaceable_answer_summaries(request: TurnRequest) -> list[dict[str, Any]]:
    """
    Показывает модели темы и сохранённые варианты допустимых замен.
    """
    replaceable_codes = frozenset(request.replaceable_question_codes)
    states_by_code = {state.question_code: state for state in request.state.questions}
    summaries: list[dict[str, Any]] = []
    for question in request.questionnaire.questions:
        if question.question_code not in replaceable_codes:
            continue
        saved_answer = states_by_code[question.question_code].answer
        if saved_answer is None:
            continue
        option_labels = {option.option_code: option.text for option in question.options}
        summaries.append(
            {
                "questionCode": question.question_code,
                "questionText": question.question_text,
                "savedOptionLabels": [option_labels[code] for code in saved_answer.option_codes],
            }
        )
    return summaries


def _build_questionnaire_prompt_payload(request: TurnRequest) -> dict[str, Any]:
    """
    Заменяет бизнес-коды и сокращает фоновые подсказки в пошаговом ходе.
    """
    from questionnaire_agent.prompts.compact_hints import compact_prompt_hint

    payload = request.questionnaire.model_dump(mode="json", by_alias=True)
    active_code = (
        request.active_question.question_code if request.active_question is not None else None
    )
    for question in payload["questions"]:
        question.pop("clarificationText", None)
        question.pop("followupClarificationText", None)
        if (
            request.answer_scope == TurnAnswerScope.ACTIVE_QUESTION
            and request.questionnaire.questionnaire_code == "AGE_6_9"
            and request.questionnaire.questionnaire_version == "age-6-9-child-1.4.0"
            and question["questionCode"] != active_code
        ):
            question["promptHint"] = compact_prompt_hint(
                question["questionCode"],
                question["promptHint"],
            )
        for option_index, option in enumerate(question["options"], start=1):
            option.pop("optionCode")
            option["optionRef"] = f"V{option_index}"
    return payload


def _build_question_state_payload(
    question_state: QuestionState,
    question: Question,
) -> dict[str, Any]:
    """
    Удаляет backend provenance и заменяет сохранённые коды ссылками V1 и далее.
    """
    answer = question_state.answer
    option_refs_by_code = {
        option.option_code: f"V{option_index}"
        for option_index, option in enumerate(question.options, start=1)
    }
    answer_payload = (
        None
        if answer is None
        else {
            "optionRefs": [option_refs_by_code[option_code] for option_code in answer.option_codes],
            "evidence": answer.evidence,
        }
    )
    return {
        "questionCode": question_state.question_code,
        "status": question_state.status.value,
        "answer": answer_payload,
        "clarificationAttempts": question_state.clarification_attempts,
        "skipReason": question_state.skip_reason,
    }


def _build_agent_decision_schema(request: TurnRequest) -> dict[str, Any]:
    """
    Ограничивает общую схему кодами и вариантами конкретного хода.
    """
    schema = AgentDecision.model_json_schema(by_alias=True, mode="validation")
    definitions = schema["$defs"]
    properties = schema["properties"]

    change_variants = _build_change_variants(request, definitions)
    grouped_variants: dict[str, list[dict[str, Any]]] = {}
    for variant in change_variants:
        question_code = variant["properties"]["questionCode"]["const"]
        grouped_variants.setdefault(question_code, []).append(variant)
    change_slots = {
        question_code: {"anyOf": [*variants, {"type": "null"}]}
        for question_code, variants in grouped_variants.items()
    }
    properties["changes"] = {
        "type": "object",
        "properties": change_slots,
        "required": list(change_slots),
        "additionalProperties": False,
    }
    properties["priorCorrection"] = {
        "anyOf": [*_build_prior_correction_variants(request), {"type": "null"}],
    }
    properties["favouriteAddition"] = {
        "anyOf": [*_build_favourite_addition_variants(request), {"type": "null"}],
    }

    clarification_variants = _build_clarification_variants(request, definitions)
    properties["clarification"] = {
        "anyOf": [*clarification_variants, {"type": "null"}],
    }
    explanation_variants = (
        []
        if request.active_question is None
        else [
            _build_question_change_variant(
                definitions["AgentExplanation"],
                request.active_question.question_code,
            )
        ]
    )
    properties["explanation"] = {
        "anyOf": [*explanation_variants, {"type": "null"}],
    }
    unknown_question_codes = [
        question_state.question_code
        for question_state in request.state.questions
        if question_state.status == QuestionStatus.UNKNOWN
        and (
            request.active_question is None
            or question_state.question_code != request.active_question.question_code
        )
    ]
    if any(question_code != "E1" for question_code in unknown_question_codes):
        unknown_question_codes = [
            question_code for question_code in unknown_question_codes if question_code != "E1"
        ]
    properties["preferredNextQuestionCode"] = {
        "anyOf": [
            *(
                [{"enum": unknown_question_codes, "type": "string"}]
                if unknown_question_codes
                else []
            ),
            {"type": "null"},
        ],
    }
    draft_codes = (
        [
            question_state.question_code
            for question_state in request.state.questions
            if question_state.status == QuestionStatus.UNKNOWN
        ]
        if request.answer_scope == TurnAnswerScope.ACTIVE_QUESTION
        and request.active_question is not None
        else []
    )
    properties["questionDraft"] = {
        "anyOf": [
            *(
                [
                    {
                        "type": "object",
                        "properties": {
                            "questionCode": {"enum": draft_codes, "type": "string"},
                            "bridgeText": {
                                "type": "string",
                                "minLength": 1,
                                "maxLength": 120,
                            },
                            "questionText": {
                                "type": "string",
                                "minLength": 1,
                                "maxLength": 240,
                            },
                            "askedQuestionCodes": {
                                "type": "array",
                                "items": {"enum": draft_codes, "type": "string"},
                                "minItems": 1,
                                "maxItems": 2,
                            },
                        },
                        "required": [
                            "questionCode",
                            "bridgeText",
                            "questionText",
                            "askedQuestionCodes",
                        ],
                        "additionalProperties": False,
                    }
                ]
                if draft_codes
                else []
            ),
            {"type": "null"},
        ],
    }
    schema["required"] = [
        *schema["required"],
        "priorCorrection",
        "favouriteAddition",
        "explanation",
        "preferredNextQuestionCode",
        "questionDraft",
    ]
    schema.pop("$defs", None)
    return schema


def _build_change_variants(
    request: TurnRequest,
    definitions: dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Создаёт допустимые операции в пределах выбранной области ответов.
    """
    questions_by_code = {
        question.question_code: question for question in request.questionnaire.questions
    }
    evidence_candidate_ids = tuple(
        candidate.candidate_id
        for candidate in build_evidence_candidates(request.current_message.content)
    ) + (FULL_MESSAGE_EVIDENCE_ID,)
    variants: list[dict[str, Any]] = []

    if request.answer_scope == TurnAnswerScope.ALL_UNANSWERED:
        for question_state in request.state.questions:
            if question_state.status != QuestionStatus.UNKNOWN:
                continue
            question = questions_by_code[question_state.question_code]
            variants.append(
                _build_interpret_answer_variant(
                    question,
                    evidence_candidate_ids,
                    replace_existing=False,
                )
            )
        return variants

    active_question = request.active_question
    if active_question is not None:
        for question_state in request.state.questions:
            if (
                question_state.status != QuestionStatus.UNKNOWN
                and question_state.question_code != active_question.question_code
            ):
                continue
            question = questions_by_code[question_state.question_code]
            variants.append(
                _build_interpret_answer_variant(
                    question,
                    evidence_candidate_ids,
                    replace_existing=False,
                )
            )
        question = questions_by_code[active_question.question_code]
        skip_variant = _build_question_change_variant(
            definitions["AgentSkipQuestionChange"],
            question.question_code,
        )
        skip_variant["properties"]["evidenceCandidateId"] = {
            "enum": list(evidence_candidate_ids),
            "type": "string",
        }
        variants.append(skip_variant)

    return variants


def _build_prior_correction_variants(request: TurnRequest) -> list[dict[str, Any]]:
    """
    Разрешает не более одной обычной замены сохранённого ответа за ход.
    """
    if request.answer_scope == TurnAnswerScope.ALL_UNANSWERED:
        return []
    questions_by_code = {
        question.question_code: question for question in request.questionnaire.questions
    }
    correction = request.answer_correction
    codes = list(request.replaceable_question_codes)
    if correction is not None and correction.mode == AnswerCorrectionMode.REPLACE:
        if correction.question_code not in codes:
            codes.append(correction.question_code)
    evidence_candidate_ids = tuple(
        candidate.candidate_id
        for candidate in build_evidence_candidates(request.current_message.content)
    ) + (FULL_MESSAGE_EVIDENCE_ID,)
    return [
        _build_interpret_answer_variant(
            questions_by_code[code],
            evidence_candidate_ids,
            replace_existing=True,
        )
        for code in codes
    ]


def _build_favourite_addition_variants(request: TurnRequest) -> list[dict[str, Any]]:
    """
    Ограничивает дополнение сохранённого множественного выбора новыми вариантами.
    """
    correction = request.answer_correction
    if correction is None or correction.mode != AnswerCorrectionMode.ADDITIVE:
        return []
    question = next(
        question
        for question in request.questionnaire.questions
        if question.question_code == correction.question_code
    )
    evidence_candidate_ids = tuple(
        candidate.candidate_id
        for candidate in build_evidence_candidates(request.current_message.content)
    ) + (FULL_MESSAGE_EVIDENCE_ID,)
    variant = _build_interpret_answer_variant(
        question,
        evidence_candidate_ids,
        replace_existing=True,
    )
    previous_state = next(
        state
        for state in request.state.questions
        if state.question_code == correction.question_code
    )
    assert previous_state.answer is not None
    selected_codes = set(previous_state.answer.option_codes)
    available_refs = [
        f"V{index}"
        for index, option in enumerate(question.options, start=1)
        if option.option_code not in selected_codes
    ]
    option_refs_schema = variant["properties"]["interpretation"]["properties"]["optionRefs"]
    option_refs_schema["items"]["enum"] = available_refs
    option_refs_schema["minItems"] = 1
    option_refs_schema["maxItems"] = min(
        len(available_refs),
        question.max_selections - len(selected_codes),
    )
    return [variant]


def _build_clarification_variants(
    request: TurnRequest,
    definitions: dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Ограничивает единственное уточнение вопросами текущей области ответа.
    """
    if request.answer_scope == TurnAnswerScope.ALL_UNANSWERED:
        question_codes = tuple(
            question_state.question_code
            for question_state in request.state.questions
            if question_state.status == QuestionStatus.UNKNOWN
        )
    elif request.active_question is not None:
        active_code = request.active_question.question_code
        states_by_code = {
            question_state.question_code: question_state
            for question_state in request.state.questions
        }
        active_state = states_by_code[active_code]
        question_codes = () if active_state.clarification_attempts >= 2 else (active_code,)
    else:
        question_codes = ()

    if not question_codes:
        return []
    variant = deepcopy(definitions["AgentClarification"])
    variant["properties"]["questionCode"] = {
        "enum": list(question_codes),
        "type": "string",
    }
    return [variant]


def _build_interpret_answer_variant(
    question: Question,
    evidence_candidate_ids: tuple[str, ...],
    *,
    replace_existing: bool,
) -> dict[str, Any]:
    """
    Создаёт типизированную смысловую операцию без бизнес-кодов вариантов.
    """
    properties = {
        "operation": {"const": "INTERPRET_ANSWER", "type": "string"},
        "questionCode": {"const": question.question_code, "type": "string"},
        "interpretation": _build_interpretation_schema(question),
        "evidenceCandidateId": {
            "enum": list(evidence_candidate_ids),
            "type": "string",
        },
        "replaceExisting": {
            "const": replace_existing,
            "type": "boolean",
        },
    }
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def _build_interpretation_schema(question: Question) -> dict[str, Any]:
    """
    Ограничивает форму смыслового ответа типом и назначением вопроса.
    """
    if question.question_type == QuestionType.SCALE_0_3:
        return _build_scale_interpretation_schema(question)
    if question.question_type == QuestionType.PAIR_CHOICE:
        return _build_pair_interpretation_schema()
    if question.question_type in {
        QuestionType.SINGLE_CHOICE,
        QuestionType.MULTI_CHOICE,
    }:
        return _build_option_selection_interpretation_schema(question)
    raise ValueError(f"Неподдерживаемый тип вопроса: {question.question_type}")


def _build_scale_interpretation_schema(question: Question) -> dict[str, Any]:
    """
    Разрешает прямой уровень и только предметно допустимые косвенные сигналы.
    """
    signals_by_meaning = {
        "SELF_RATED_SKILL": [
            "NEGATIVE_ACTIVITY_ATTITUDE",
            "UNQUALIFIED_ACTIVITY_DISLIKE",
            "EXPLICIT_ACTIVITY_AVOIDANCE",
            "POSITIVE_ACTIVITY_ATTITUDE",
        ],
        "ENDURANCE_SELF_RATING": [
            "POSITIVE_VIGOROUS_ACTIVITY_ATTITUDE",
            "NEGATIVE_SCHOOL_PE_ATTITUDE",
        ],
        "VISUAL_ATTENTION_FREQUENCY": ["POSITIVE_SUBTYPE_INTEREST"],
        "FREQUENCY": ["SPONTANEOUS_MUSIC_RECALL"],
        "FOCUS_DURATION": ["SUSTAINED_CALM_FOCUS"],
        "HANDCRAFT_ATTITUDE": [
            "SUSTAINED_HANDCRAFT_ENGAGEMENT",
            "PERSONAL_HANDCRAFT_ACHIEVEMENT",
        ],
    }
    allowed_signals = signals_by_meaning.get(question.answer_meaning, [])
    signal_items: dict[str, Any] = {"type": "string"}
    if allowed_signals:
        signal_items["enum"] = allowed_signals
    properties = {
        "kind": {"const": "SCALE", "type": "string"},
        "directLevel": {
            "anyOf": [
                {"enum": [0, 1, 2, 3], "type": "integer"},
                {"type": "null"},
            ]
        },
        "indirectSignals": {
            "type": "array",
            "items": signal_items,
            "minItems": 0,
            "maxItems": len(allowed_signals),
        },
    }
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def _build_pair_interpretation_schema() -> dict[str, Any]:
    """
    Описывает сторону и силу парного предпочтения независимо от формулировки.
    """
    properties = {
        "kind": {"const": "PAIR_PREFERENCE", "type": "string"},
        "side": {"enum": ["FIRST", "SECOND"], "type": "string"},
        "strength": {"enum": ["PREFERRED", "EXCLUSIVE"], "type": "string"},
    }
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def _build_option_selection_interpretation_schema(
    question: Question,
) -> dict[str, Any]:
    """
    Ограничивает позиционные ссылки реально показанными вариантами вопроса.
    """
    properties = {
        "kind": {"const": "OPTION_SELECTION", "type": "string"},
        "optionRefs": {
            "type": "array",
            "items": {
                "enum": [
                    f"V{option_index}" for option_index in range(1, len(question.options) + 1)
                ],
                "type": "string",
            },
            "minItems": max(1, question.min_selections),
            "maxItems": question.max_selections,
        },
    }
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def _build_question_change_variant(
    template: dict[str, Any],
    question_code: str,
) -> dict[str, Any]:
    """
    Копирует вариант решения и фиксирует разрешённый код вопроса.
    """
    variant = deepcopy(template)
    variant["properties"]["questionCode"] = {
        "const": question_code,
        "type": "string",
    }
    return variant
